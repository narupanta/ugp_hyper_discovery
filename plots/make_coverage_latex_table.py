#!/usr/bin/env python3
"""
LaTeX table of coverage studies, one row per test case:
  per-term rates (true terms: interval covers the true value; terms not in the true model: filtered out), their mean,
  the distilled energy RMSE / R^2 / 95% EC (mean +- std over all seed x init runs, validation load steps) and the
  median model: the run in the middle of the ranking by RMSE (low first), R^2 (high first) and |EC - 95| (closest to
  nominal first), ranks averaged.

Needs coverage_summary.json (validation/distillation_coverage_study.py, with candidate_terms) and each run's
validation_metrics.json (plots/plot_distilled_r2_energy.py).

Usage: python3 plots/make_coverage_latex_table.py <study_dir>:Isihara [<study_dir>:Label ...] [--out table.tex]
Default output: <first study>/coverage_table.tex
"""
import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from summarize_coverage_metrics import read  # noqa: E402

TERM_TEX = {"C10": "C_{10}", "C01": "C_{01}", "C20": "C_{20}", "C11": "C_{11}", "C02": "C_{02}", "C30": "C_{30}",
            "C21": "C_{21}", "C12": "C_{12}", "C03": "C_{03}", "E": "E", "D1": "D_1", "D2": "D_2", "D3": "D_3",
            "C42": "C_{42}", "C43": "C_{43}", "C44": "C_{44}", "C62": "C_{62}", "C63": "C_{63}", "C64": "C_{64}"}


def tex_term(n):
    if n in TERM_TEX:
        return f"${TERM_TEX[n]}$"
    if n.startswith("mu") or n.startswith("alpha"):
        return "$\\" + ("mu" if n.startswith("mu") else "alpha") + "_{" + n.lstrip("mualph") + "}$"
    return n


def load_case(study):
    summ = json.load(open(os.path.join(study, "coverage_summary.json")))
    if "candidate_terms" not in summ:
        raise SystemExit(f"{study}: coverage_summary.json has no candidate_terms; rerun the study with --evaluate_only")
    k = max(summ["checkpoints"], key=int)
    per = summ["checkpoints"][k]["per_parameter"]
    terms = summ["candidate_terms"]
    runs = {}
    for s in summ["noise_seeds"]:
        for m in range(summ["n_inits"]):
            r = read(os.path.join(study, f"seed{s}", f"init{m}"), "total")
            if r is not None:
                runs[(s, m)] = r["dist"]
    if not runs:
        raise SystemExit(f"{study}: no validation_metrics.json in the runs")
    keys = sorted(runs)
    rm = np.array([runs[k]["rmse"] for k in keys])
    r2 = np.array([runs[k]["r2"] for k in keys])
    ec = np.array([runs[k]["coverage"] for k in keys])
    rank = lambda x: np.argsort(np.argsort(x, kind="stable"), kind="stable")
    score = (rank(rm) + rank(-r2) + rank(np.abs(ec - 95.0))) / 3.0
    order = np.argsort(score, kind="stable")
    med = keys[int(order[(len(keys) - 1) // 2])]
    return dict(terms=terms, per=per, n=len(keys), rmse=rm, r2=r2, ec=ec, median=med, median_vals=runs[med])


def pm(x, d):
    return f"${np.mean(x):.{d}f} \\pm {np.std(x, ddof=1):.{d}f}$"


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("cases", nargs="+", help="<study_dir>:<label>")
    p.add_argument("--out", default=None)
    args = p.parse_args()
    cases = []
    for c in args.cases:
        path, _, label = c.rpartition(":") if ":" in c else (c, "", os.path.basename(c))
        cases.append((label or os.path.basename(path), load_case(os.path.abspath(path))))

    same = all(c["terms"] == cases[0][1]["terms"] for _, c in cases)
    if same:            # grouped header: covered (true terms) | filtered (absent terms)
        tt, at = cases[0][1]["terms"]["true"], cases[0][1]["terms"]["absent"]
        cols = tt + at
        head1 = (f" & \\multicolumn{{{len(tt)}}}{{c}}{{Covered (\\%)}} & \\multicolumn{{{len(at)}}}{{c}}{{Filtered (\\%)}}"
                 f" & & \\multicolumn{{3}}{{c}}{{Discovered model}} & \\\\")
        rules = (f"\\cmidrule(lr){{2-{1 + len(tt)}}} \\cmidrule(lr){{{2 + len(tt)}-{1 + len(cols)}}} "
                 f"\\cmidrule(lr){{{3 + len(cols)}-{5 + len(cols)}}}")
    else:               # different true models: one column per term, true terms in bold
        cols = []
        for _, c in cases:
            for n in c["terms"]["true"] + c["terms"]["absent"]:
                if n not in cols:
                    cols.append(n)
        head1 = f" & \\multicolumn{{{len(cols)}}}{{c}}{{Per term (\\%)}} & & \\multicolumn{{3}}{{c}}{{Discovered model}} & \\\\"
        rules = f"\\cmidrule(lr){{2-{1 + len(cols)}}} \\cmidrule(lr){{{3 + len(cols)}-{5 + len(cols)}}}"
    head2 = ("Test case & " + " & ".join(tex_term(n) for n in cols)
             + " & Mean (\\%) & RMSE & $R^2$ & EC$_{95}$ (\\%) & Median model \\\\")
    L = ["% generated by plots/make_coverage_latex_table.py; needs \\usepackage{booktabs}", "\\begin{table}[t]",
         "\\centering", "\\small", "\\setlength{\\tabcolsep}{4pt}",
         "\\begin{tabular}{l" + "c" * len(cols) + "c" + "ccc" + "c}", "\\toprule", head1, rules, head2, "\\midrule"]
    for label, c in cases:
        cells = []
        for n in cols:
            if n in c["per"] and (n in c["terms"]["true"] or n in c["terms"]["absent"]):
                v = f"{c['per'][n]:.0f}"
                cells.append(f"$\\mathbf{{{v}}}$" if (not same and n in c["terms"]["true"]) else v)
            else:
                cells.append("--")
        mean_t = np.mean([c["per"][n] for n in c["terms"]["true"] + c["terms"]["absent"]])
        s, m = c["median"]
        L.append(f"{label} & " + " & ".join(cells) + f" & {mean_t:.1f} & {pm(c['rmse'], 3)} & {pm(c['r2'], 4)} & "
                 f"{pm(c['ec'], 1)} & seed {s}, init {m} \\\\")
    n_runs = cases[0][1]["n"]
    note = ("true terms (bold): interval covers the true value; other terms: filtered out" if not same else
            "covered: the 95\\% interval contains the true value; filtered: a term not in the true model is pruned "
            "(its interval does not exclude 0)")
    L += ["\\bottomrule", "\\end{tabular}",
          f"\\caption{{Distilled-parameter coverage and accuracy over {n_runs} runs (noise seeds $\\times$ flow "
          f"initialisations). Per term: {note}; Mean: average over the terms. Discovered model: strain-energy RMSE, "
          f"$R^2$ and 95\\% coverage on the validation load steps, mean $\\pm$ std over the runs. Median model: the "
          f"run in the middle of the ranking by RMSE, $R^2$ and $|\\mathrm{{EC}}_{{95}} - 95|$ (ranks averaged).}}",
          "\\label{tab:coverage}", "\\end{table}"]
    out = args.out or os.path.join(os.path.abspath(args.cases[0].rpartition(":")[0] or args.cases[0]), "coverage_table.tex")
    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    for label, c in cases:
        v = c["median_vals"]
        print(f"% {label}: median model seed {c['median'][0]} init {c['median'][1]}: RMSE {v['rmse']:.4f}, "
              f"R2 {v['r2']:.4f}, EC {v['coverage']:.1f}")
    print(out)


if __name__ == "__main__":
    main()
